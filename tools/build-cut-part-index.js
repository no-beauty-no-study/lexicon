#!/usr/bin/env node
/* ============================================================
   Build data/vocab/VOCAB_CUT_PART_INDEX_LITE.js — the reverse index from a
   word's cut PART (root / prefix / suffix) to every word that shares it, so the
   word card's clickable cut (com·mut·e) can jump into Words Garden filtered to
   that root's pool.

   Source of truth: WORD_OWL cuts (word -> {slash:"com/mut/e", zh:"共同/改变/e"}).
   Only 2851 words carry a cut, and some same-root words (mutate, mutation)
   have none — so for real ROOT parts we ALSO pull in the runtime's
   family/kin/group members that contain the part. Common affixes (prefixes /
   suffixes like com-, -al, -tion) are indexed but flagged non-root, so the
   word card only makes ROOTS clickable (clicking "com" or "ly" is noise).

   Emits window.VOCAB_CUT_PART_INDEX_LITE = {
     parts:  { mut: ["commute","mutable","mutate",...], ... },  // sorted, unique
     partZh: { mut: "改变", ... },                              // gloss per part
     roots:  { mut: 1, spect: 1, ... }                         // clickable parts
   }
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");
const V = path.join(__dirname, "..", "data", "vocab");
global.window = {};
[
  "VOCAB_WORD_CONTENT_REGISTRY_LITE", "VOCAB_READING_WORDS_LITE",
  "VOCAB_FAMILY_SHARED_CLUSTERS_LITE", "VOCAB_KIN_CLEAN_LITE",
  "VOCAB_KIN_HEAD_BRIDGE_LITE", "VOCAB_GROUP_CLEAN_LITE",
  "VOCAB_WORD_ENTRY_POLICY_LITE", "VOCAB_ENTRY_VISIBILITY_POLICY_LITE",
  "VOCAB_HEAD_TO_FAMILY_KIN_NAV_LITE", "VOCAB_KIN_NAV_EXPANSION_PATCH_V149",
  "VOCAB_KIN_CONTROL_VARIABLE_PATCH_V153", "VOCAB_PREFIX_KIN_STRONG_OVERRIDE_PATCH_V156",
  "VOCAB_DOTTED_LITE", "VOCAB_PROPER_SMALL_CARDS_FINAL",
  "VOCAB_CLAUDE_SUPPLEMENT_V158", "VOCAB_CLAUDE_SUPPLEMENT_V159",
  "wordOwl", "VOCAB_RUNTIME_HELPERS",
].forEach(f => require(path.join(V, f + ".js")));

const W = global.window.WORD_OWL || {};
const R = global.window.VocabRuntime;

// Common English prefixes + suffixes — indexed for completeness but NOT made
// clickable roots, and never used to enrich (they'd pull in unrelated words).
const AFFIX = new Set([
  // prefixes
  "a", "ab", "ad", "be", "co", "com", "con", "de", "dis", "em", "en", "ex",
  "fore", "im", "in", "inter", "intro", "ir", "mis", "non", "ob", "out", "over",
  "per", "post", "pre", "pro", "re", "semi", "sub", "super", "trans", "un",
  "under", "up", "anti", "auto", "counter", "bi", "tri", "uni", "mono", "multi",
  // suffixes
  "able", "ible", "al", "ial", "ance", "ence", "ancy", "ency", "ant", "ent",
  "ar", "ary", "ate", "ation", "ition", "tion", "sion", "ion", "dom", "ed",
  "ee", "er", "or", "ery", "ese", "ess", "est", "ful", "fy", "ic", "ical",
  "ify", "ing", "ish", "ism", "ist", "ite", "ity", "ive", "ize", "ise", "less",
  "like", "ly", "ment", "ness", "ous", "ship", "th", "ty", "ure", "ward",
  "wise", "y", "e", "s", "es", "age", "ous", "ious", "eous",
]);

const parts = new Map();    // part -> Set(words)
const partZh = new Map();   // part -> first non-empty zh gloss
function seg(slash) { return String(slash || "").split("/").map(s => s.trim().toLowerCase()); }

// Pass 1 — direct cut-segment membership + the parallel Chinese gloss.
for (const word of Object.keys(W)) {
  const cut = W[word] && W[word].cut;
  if (!cut || !cut.slash || cut.slash.indexOf("/") < 0) continue;
  const segs = seg(cut.slash), zhs = seg(cut.zh);
  segs.forEach((p, i) => {
    if (p.length < 2 || !/^[a-z]+$/.test(p)) return;
    if (!parts.has(p)) parts.set(p, new Set());
    parts.get(p).add(word.toLowerCase());
    const z = (zhs[i] || "").trim();
    if (z && /[一-鿿]/.test(z) && !partZh.has(p)) partZh.set(p, z);
  });
}

// Pass 2 — for ROOT parts (len ≥ 3, not an affix), pull in the runtime's
// family/kin/group members that contain the root, so same-root words that lack
// their own cut (mutate, mutation) still land in the pool.
function membersOf(w) {
  let bc = null;
  try { bc = R && R.getBigCard ? R.getBigCard(w) : null; } catch (_) {}
  if (!bc) return [];
  return [].concat(bc.family_members || [], bc.kin_members || [], bc.group || [])
    .map(m => String(m.word || "").toLowerCase()).filter(Boolean);
}
for (const [p, set] of parts) {
  if (p.length < 3 || AFFIX.has(p)) continue;
  for (const w of [...set]) for (const m of membersOf(w)) if (m.includes(p)) set.add(m);
}

// Emit — keep parts with ≥ 2 words; mark real roots (clickable).
const outParts = {}, outZh = {}, outRoots = {};
for (const [p, set] of [...parts].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (set.size < 2) continue;
  outParts[p] = [...set].sort();
  if (partZh.has(p)) outZh[p] = partZh.get(p);
  if (p.length >= 3 && !AFFIX.has(p)) outRoots[p] = 1;
}

const out = "/* AUTO-GENERATED by tools/build-cut-part-index.js — do not edit by hand.\n"
  + "   cut PART -> words sharing it (for the word card's clickable cut → Words Garden). */\n"
  + "window.VOCAB_CUT_PART_INDEX_LITE = " + JSON.stringify({ parts: outParts, partZh: outZh, roots: outRoots }) + ";\n";
fs.writeFileSync(path.join(V, "VOCAB_CUT_PART_INDEX_LITE.js"), out);

const nRoots = Object.keys(outRoots).length, nParts = Object.keys(outParts).length;
console.log(`parts: ${nParts} (roots ${nRoots}) | mut -> ${(outParts.mut || []).join(", ")}`);
console.log(`spect -> ${(outParts.spect || []).slice(0, 12).join(", ")}`);
