#!/usr/bin/env node
/* ============================================================
   Parse the word-owl warehouse (data/vocab/word_owl.src.md) into a runtime
   supplement: data/vocab/wordOwl.js → window.WORD_OWL.

   Per word the warehouse gives: IPA, a `cut:` (slash decomposition + a
   slash-aligned Chinese gloss of the pieces), then one or more MEANINGS, each
   with POS + Chinese + an English gloss (= that meaning's synonyms) + optional
   example/example_zh + phrases.

   Emitted shape (keyed by lowercased word):
     { ipa, cut:{slash, zh},
       meanings:[ { pos, zh, gloss, syns:[…], example, example_zh,
                    phrases:[{en,zh}] } ] }
   plus window.WORD_OWL_DEMOTED = Set of small-card-only words.
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");
const SRC = path.join(__dirname, "..", "data", "vocab", "word_owl.src.md");
const DEM = path.join(__dirname, "..", "data", "vocab", "word_owl_demotions.src.md");
const OUT = path.join(__dirname, "..", "data", "vocab", "wordOwl.js");

const HEAD = /^([A-Za-z][A-Za-z'’.\- ]*?)(?:\s+\[([^\]]*)\])?$/;  // "word" or "word [IPA]"
const POS_RE = /^([a-z]{1,5}\.)\s+/;                            // v. n. adj. …
// split "中文…  english gloss" → [zh, gloss]
function splitZhGloss(s) {
  const m = s.match(/^([^A-Za-z]*?)\s*([A-Za-z].*)?$/);
  return m ? [(m[1] || "").trim().replace(/\s+$/, ""), (m[2] || "").trim()] : [s.trim(), ""];
}
function splitSyns(gloss) {
  return gloss.split(/[,;，；]/).map(s => s.trim()).filter(Boolean);
}

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/);
const out = {};
let cur = null, state = "", meaning = null;

function flushMeaning() { if (cur && meaning && (meaning.zh || meaning.gloss)) cur.meanings.push(meaning); meaning = null; }
function startWord(word, ipa) {
  flushMeaning();
  cur = { ipa: ipa.trim(), cut: { slash: "", zh: "" }, meanings: [] };
  out[word.toLowerCase()] = cur;
  state = "afterHead"; cutLines = [];
}
let cutLines = [];

for (let i = 0; i < lines.length; i++) {
  const raw = lines[i];
  const line = raw.trim();
  if (line.startsWith("#")) continue;

  // A word header is any clean word line IMMEDIATELY followed by "cut:"
  // (many warehouse words have no [IPA], so the "cut:" lookahead is the
  // reliable delimiter).
  const next = (lines[i + 1] || "").trim();
  const h = HEAD.exec(line);
  if (next === "cut:" && h && !/^(example|example_zh|phrase|cut)\b/.test(line)) {
    startWord(h[1].trim(), h[2] || ""); continue;
  }
  if (!cur) continue;

  if (line === "cut:") { state = "cut"; cutLines = []; continue; }
  if (state === "cut") {
    // collect exactly the slash line then the cut-zh line (either may be blank)
    cutLines.push(line);
    if (cutLines.length === 2) {
      cur.cut.slash = cutLines[0] || "";
      cur.cut.zh = cutLines[1] || "";
      state = "meanings";
    }
    continue;
  }
  if (state === "meanings" || state === "afterHead") {
    if (!line) continue;
    if (/^example_zh:/i.test(line)) { if (meaning) meaning.example_zh = line.replace(/^example_zh:\s*/i, ""); continue; }
    if (/^example:/i.test(line))    { if (meaning) meaning.example = line.replace(/^example:\s*/i, ""); continue; }
    if (/^phrase:/i.test(line)) {
      if (meaning) {
        const body = line.replace(/^phrase:\s*/i, "");
        const dash = body.split(/\s+[-–—]\s+/);
        meaning.phrases.push({ en: (dash[0] || "").trim(), zh: (dash[1] || "").trim() });
      }
      continue;
    }
    // otherwise: a new meaning line (optionally "N." numbered, optionally POS)
    flushMeaning();
    let t = line.replace(/^\d+\.\s*/, "");
    let pos = "";
    const pm = POS_RE.exec(t);
    if (pm) { pos = pm[1]; t = t.slice(pm[0].length); }
    const [zh, gloss] = splitZhGloss(t);
    meaning = { pos, zh, gloss, syns: splitSyns(gloss), example: "", example_zh: "", phrases: [] };
  }
}
flushMeaning();

// demotions → small-card-only set
const demoted = fs.readFileSync(DEM, "utf8").split(/\r?\n/)
  .map(s => s.trim()).filter(s => s && !s.startsWith("#"));

const nWords = Object.keys(out).length;
const nMeanings = Object.values(out).reduce((a, w) => a + w.meanings.length, 0);
const nCut = Object.values(out).filter(w => w.cut.slash).length;

fs.writeFileSync(OUT,
  "/* AUTO-GENERATED by tools/parse-word-owl.js — do not hand-edit. */\n" +
  "window.WORD_OWL = " + JSON.stringify(out) + ";\n" +
  "window.WORD_OWL_DEMOTED = new Set(" + JSON.stringify(demoted) + ");\n");

console.log(`words ${nWords}, meanings ${nMeanings}, with-cut ${nCut}, demoted ${demoted.length}`);
console.log("wrote", path.relative(path.join(__dirname, ".."), OUT), "(" + (fs.statSync(OUT).size / 1048576).toFixed(2) + " MB)");
